#!/usr/bin/env node
/**
 * Generate the `dnd5e.applications.*` API-surface fragments from the runtime `_module.mjs` files.
 * Mirrors each subdir's public export names into an open `declare global` namespace, exposing every
 * application class as BOTH a value (`const` → constructor) and, for classes, a `type` (instance).
 * Run: node scripts/gen-applications-api.mjs
 */
import fs from "node:fs";
import path from "node:path";

const RT = "_research/dnd5e/module/applications";
const SRC = "src/module/applications";
const OUT = "src/module/_api";

// subdir -> namespace member name
const SUBDIRS = {
  activity: "activity",
  actor: "actor",
  advancement: "advancement",
  calendar: "calendar",
  combat: "combat",
  components: "components",
  dice: "dice",
  item: "item",
  journal: "journal",
  "region-behavior": "regionBehavior",
  settings: "settings",
  shared: "shared",
};

/** Determine if `relNoExt` (relative to SRC) default-exports a class (→ emit type alias) or not. */
function defaultKind(relNoExt, named) {
  const file = path.join(SRC, relNoExt + ".d.mts");
  if (!fs.existsSync(file)) return { ok: false };
  const txt = fs.readFileSync(file, "utf8");
  if (named) {
    const isClass = new RegExp(`declare class ${named}\\b`).test(txt) || new RegExp(`export declare class ${named}\\b`).test(txt);
    return { ok: true, named, isClass };
  }
  const m = txt.match(/export default (\w+)\s*;/);
  if (!m) return { ok: true, isClass: false, viaDefault: true };
  const id = m[1];
  const isClass = new RegExp(`declare class ${id}\\b`).test(txt);
  return { ok: true, isClass, viaDefault: true };
}

/** Emit member lines for a default-export member. */
function emitDefault(member, relNoExt, indent) {
  const imp = `../applications/${relNoExt}.mjs`;
  const k = defaultKind(relNoExt, null);
  const lines = [`${indent}const ${member}: typeof import("${imp}").default;`];
  if (k.ok && k.isClass) lines.push(`${indent}type ${member} = import("${imp}").default;`);
  return lines.join("\n");
}

/** Emit member lines for a named-export member. */
function emitNamed(member, relNoExt, exportName, indent) {
  const imp = `../applications/${relNoExt}.mjs`;
  const k = defaultKind(relNoExt, exportName);
  const lines = [`${indent}const ${member}: typeof import("${imp}").${exportName};`];
  if (k.ok && k.isClass) lines.push(`${indent}type ${member} = import("${imp}").${exportName};`);
  return lines.join("\n");
}

/** Parse `export {default as Name} from "./x.mjs"` lines in a _module.mjs. */
function parseDefaultExports(moduleTxt, subdir) {
  const out = [];
  const re = /export\s*\{\s*default as (\w+)\s*\}\s*from\s*"\.\/([^"]+)\.mjs"/g;
  let m;
  while ((m = re.exec(moduleTxt))) out.push({ member: m[1], rel: `${subdir}/${m[2]}` });
  return out;
}

function wrap(nsBody, ns) {
  return `/**
 * AUTO-GENERATED by scripts/gen-applications-api.mjs — do not edit by hand.
 * API surface for \`${ns}\` (mirrors the runtime _module.mjs public exports).
 */

declare global {
  namespace ${ns} {
${nsBody}
  }
}

export {};
`;
}

const generated = [];

for (const [subdir, nsName] of Object.entries(SUBDIRS)) {
  const modFile = path.join(RT, subdir, "_module.mjs");
  if (!fs.existsSync(modFile)) continue;
  const txt = fs.readFileSync(modFile, "utf8");
  const body = [];

  if (subdir === "components") {
    // components: `import Name from "./file.mjs"` then `export { Name, ... }`
    const imports = {};
    const reI = /import\s+(\w+)\s+from\s+"\.\/([^"]+)\.mjs"/g;
    let m;
    while ((m = reI.exec(txt))) imports[m[1]] = `${subdir}/${m[2]}`;
    const exp = txt.match(/export\s*\{([^}]+)\}\s*;/s);
    const names = exp ? exp[1].split(",").map((s) => s.trim()).filter(Boolean) : [];
    for (const name of names) {
      if (!imports[name]) continue;
      body.push(emitDefault(name, imports[name], "    "));
    }
  } else {
    for (const { member, rel } of parseDefaultExports(txt, subdir)) {
      body.push(emitDefault(member, rel, "    "));
    }
    // settings: nested `export * as sidebar from "./sidebar.mjs"`
    if (subdir === "settings" && /export \* as sidebar/.test(txt)) {
      body.push(`    namespace sidebar {`);
      body.push(`      const renderSettings: typeof import("../applications/settings/sidebar.mjs").renderSettings;`);
      body.push(`    }`);
    }
  }

  const out = wrap(body.join("\n"), `dnd5e.applications.${nsName}`);
  const outFile = path.join(OUT, `applications-${nsName}.d.mts`);
  fs.writeFileSync(outFile, out);
  generated.push(outFile);
}

// Top-level loose members from applications/_module.mjs
{
  const txt = fs.readFileSync(path.join(RT, "_module.mjs"), "utf8");
  const body = [];
  // export {default as Name} from "./file.mjs"
  const re = /export\s*\{\s*default as (\w+)\s*\}\s*from\s*"\.\/([^"]+)\.mjs"/g;
  let m;
  while ((m = re.exec(txt))) body.push(emitDefault(m[1], m[2], "    "));
  // named: export {A, B} from "./token-config.mjs"
  const reN = /export\s*\{\s*([\w,\s]+?)\s*\}\s*from\s*"\.\/([^"]+)\.mjs"/g;
  while ((m = reN.exec(txt))) {
    if (/default as/.test(m[0])) continue;
    const names = m[1].split(",").map((s) => s.trim()).filter(Boolean);
    for (const n of names) body.push(emitNamed(n, m[2], n, "    "));
  }
  const out = wrap(body.join("\n"), "dnd5e.applications");
  const outFile = path.join(OUT, "applications-root.d.mts");
  fs.writeFileSync(outFile, out);
  generated.push(outFile);
}

console.log("generated:\n" + generated.map((g) => "  " + g).join("\n"));
